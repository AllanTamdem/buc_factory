def check_graph_ambiguity(graph: dict[str, set[str]]) -> tuple[bool, str]:
    """BFS check: return (True, '') if no pair of nodes has >1 directed path.

    Power BI rejects models where two tables are connected by both a direct FK
    and a transitive chain (A→B→C plus A→C). The error message names the direct
    edge, the full transitive chain, and the exact fix to make the retry actionable.
    """
    from collections import deque

    for u, neighbors in graph.items():
        for v in list(neighbors):
            visited: set[str] = {u}
            parent: dict[str, str] = {}
            queue: deque[str] = deque()
            for nb in neighbors:
                if nb != v and nb not in visited:
                    visited.add(nb)
                    parent[nb] = u
                    queue.append(nb)

            while queue:
                cur = queue.popleft()
                if cur == v:
                    chain, node = [v], v
                    while node in parent:
                        node = parent[node]
                        chain.append(node)
                    chain_str = " → ".join(reversed(chain))
                    return (
                        False,
                        f"AMBIGUOUS RELATIONSHIP: '{u}' → '{v}' exists as a direct FK "
                        f"AND as the transitive chain [{chain_str}]. "
                        f"Power BI rejects models with two paths between the same tables. "
                        f"FIX: in the '{u}' table, set fk_to: null for the column that "
                        f"points directly to '{v}' (keep the column value, just remove "
                        f"the FK arrow). The transitive chain [{chain_str}] is sufficient.",
                    )
                for nb in graph.get(cur, set()):
                    if nb not in visited:
                        visited.add(nb)
                        parent[nb] = cur
                        queue.append(nb)

    return True, ""


def parse_tmdl_relationships(model_tmdl: str) -> dict[str, set[str]]:
    """Parse relationship blocks from model.tmdl; return a directed adjacency dict.

    Handles both TMDL formats:
      fromColumn: FactTable.col  /  toColumn: DimTable.col
    """
    graph: dict[str, set[str]] = {}
    from_re = re.compile(r"fromColumn:\s*(\w+)\.", re.IGNORECASE)
    to_re = re.compile(r"toColumn:\s*(\w+)\.", re.IGNORECASE)

    in_rel = False
    from_table = to_table = None
    for line in model_tmdl.splitlines():
        stripped = line.strip()
        if stripped.lower().startswith("relationship "):
            in_rel = True
            from_table = to_table = None
            continue
        if in_rel:
            m = from_re.match(stripped)
            if m:
                from_table = m.group(1)
            m = to_re.match(stripped)
            if m:
                to_table = m.group(1)
            if not stripped or (
                not stripped.startswith("#")
                and ":" not in stripped
                and not stripped.lower().startswith("relationship")
            ):
                if from_table and to_table and from_table != to_table:
                    graph.setdefault(from_table, set()).add(to_table)
                in_rel = False
                from_table = to_table = None

    if in_rel and from_table and to_table and from_table != to_table:
        graph.setdefault(from_table, set()).add(to_table)

    return graph


def check_relationship_coherence(schema: dict[str, Any]) -> tuple[bool, str]:
    """Verify the FK graph in data_schema.json has no alternative paths."""
    graph: dict[str, set[str]] = {}
    for file_info in schema.get("files", []):
        from_table = file_info["filename"].replace(".csv", "")
        graph.setdefault(from_table, set())
        for col in file_info.get("columns", []):
            fk_to = col.get("fk_to")
            if fk_to and str(fk_to).lower() not in ("null", "none", ""):
                to_table = str(fk_to).split(".")[0].replace(".csv", "").strip()
                if to_table and to_table != from_table:
                    graph[from_table].add(to_table)
    return check_graph_ambiguity(graph)
